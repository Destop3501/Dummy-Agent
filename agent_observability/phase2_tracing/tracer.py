import functools
import inspect
import json
import logging
import threading
from contextvars import ContextVar
from typing import Any, Callable, Dict, List, Optional
from agent_observability.phase2_tracing.models import (
    ErrorPayload,
    ExecutionTraceSpan,
    SpanStatus,
    SpanType,
)

logger = logging.getLogger("agent_observability.tracer")

# Context variables for tracing spans hierarchically across threads/coroutines
_CURRENT_TRACE_ID: ContextVar[Optional[str]] = ContextVar("current_trace_id", default=None)
_CURRENT_SPAN_ID: ContextVar[Optional[str]] = ContextVar("current_span_id", default=None)


class TraceCollector:
    """
    Central repository for traces generated by the tracking layer.
    Allows real-time subscription for Phase 3 (Observer / Evaluator Node).
    """

    def __init__(self):
        self._lock = threading.Lock()
        self._traces: List[ExecutionTraceSpan] = []
        self._listeners: List[Callable[[ExecutionTraceSpan], None]] = []

    def add_span(self, span: ExecutionTraceSpan) -> None:
        """Record a completed trace span and broadcast to listeners."""
        with self._lock:
            self._traces.append(span)

        # Notify any subscribed observers (e.g. Phase 3 evaluator)
        for listener in list(self._listeners):
            try:
                listener(span)
            except Exception as listener_err:
                logger.error(f"Error in trace listener callback: {listener_err}")

    def add_listener(self, callback: Callable[[ExecutionTraceSpan], None]) -> None:
        """Register a real-time listener for generated traces."""
        with self._lock:
            if callback not in self._listeners:
                self._listeners.append(callback)

    def remove_listener(self, callback: Callable[[ExecutionTraceSpan], None]) -> None:
        """Unregister a listener."""
        with self._lock:
            if callback in self._listeners:
                self._listeners.remove(callback)

    def get_all_traces(self) -> List[ExecutionTraceSpan]:
        """Return a copy of all recorded traces."""
        with self._lock:
            return list(self._traces)

    def get_traces_as_json(self, indent: int = 2) -> str:
        """Export all traces as a formatted JSON array string."""
        with self._lock:
            return json.dumps([json.loads(s.to_json()) for s in self._traces], indent=indent)

    def clear(self) -> None:
        """Clear recorded traces."""
        with self._lock:
            self._traces.clear()


# Global default collector
default_collector = TraceCollector()


def get_current_trace_id() -> Optional[str]:
    return _CURRENT_TRACE_ID.get()


def set_current_trace_id(trace_id: Optional[str]) -> None:
    _CURRENT_TRACE_ID.set(trace_id)


def trace_prompt(
    name: Optional[str] = None,
    collector: Optional[TraceCollector] = None,
):
    """
    Decorator-based tracking layer for prompt submissions and agent responses.
    Intercepts the prompt, tracks latency, catches errors, and logs structured JSON traces.
    """
    active_collector = collector or default_collector

    def decorator(func: Callable[..., Any]) -> Callable[..., Any]:
        op_name = name or func.__name__

        @functools.wraps(func)
        def wrapper(*args: Any, **kwargs: Any) -> Any:
            parent_id = _CURRENT_SPAN_ID.get()
            span = ExecutionTraceSpan(
                parent_span_id=parent_id,
                span_type=SpanType.PROMPT,
                name=op_name,
                inputs={"args": [str(a) for a in args], "kwargs": {k: str(v) for k, v in kwargs.items()}},
            )
            # Bind trace context
            trace_token = _CURRENT_TRACE_ID.set(span.trace_id)
            span_token = _CURRENT_SPAN_ID.set(span.span_id)

            try:
                result = func(*args, **kwargs)
                span.finish_success(result)
                active_collector.add_span(span)
                return result
            except Exception as exc:
                span.finish_failure(exc)
                active_collector.add_span(span)
                raise
            finally:
                _CURRENT_TRACE_ID.reset(trace_token)
                _CURRENT_SPAN_ID.reset(span_token)

        return wrapper

    return decorator


def trace_tool(
    name: Optional[str] = None,
    collector: Optional[TraceCollector] = None,
    reraise: bool = True,
):
    """
    Decorator-based tracking layer for tool execution.
    Intercepts every tool call, inputs, execution latency, and exact error payloads
    (including full stack trace). Generates structured JSON logs.
    """
    active_collector = collector or default_collector

    def decorator(func: Callable[..., Any]) -> Callable[..., Any]:
        tool_name = name or func.__name__

        @functools.wraps(func)
        def wrapper(*args: Any, **kwargs: Any) -> Any:
            parent_id = _CURRENT_SPAN_ID.get()
            current_trace = _CURRENT_TRACE_ID.get()

            # Normalize inputs into dictionary for structured telemetry
            sig = inspect.signature(func)
            bound_args = sig.bind_partial(*args, **kwargs)
            bound_args.apply_defaults()
            inputs_dict = {k: v for k, v in bound_args.arguments.items()}

            span = ExecutionTraceSpan(
                trace_id=current_trace or ExecutionTraceSpan.model_fields["trace_id"].default_factory(),
                parent_span_id=parent_id,
                span_type=SpanType.TOOL,
                name=tool_name,
                inputs=inputs_dict,
            )
            span_token = _CURRENT_SPAN_ID.set(span.span_id)

            try:
                result = func(*args, **kwargs)
                span.finish_success(result)
                active_collector.add_span(span)
                return result
            except Exception as exc:
                span.finish_failure(exc, details={"tool_inputs": inputs_dict})
                active_collector.add_span(span)
                if reraise:
                    raise
                return {"error": str(exc), "status": "failed", "span_id": span.span_id}
            finally:
                _CURRENT_SPAN_ID.reset(span_token)

        return wrapper

    return decorator
